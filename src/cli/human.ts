/**
 * Saída para pessoas no terminal: tabelas alinhadas, frases curtas e nenhuma sigla interna.
 * Só aparece quando a saída é um terminal (ou com `--format table`); em pipe e no CI fica o formato
 * de linhas com tab, que é estável para scripts.
 */
import { styleText } from 'node:util';

type Style = Parameters<typeof styleText>[0];

/** Cor só se o destino for terminal e a pessoa não tiver pedido `NO_COLOR`. */
export function paint(style: Style, text: string, stream: NodeJS.WriteStream = process.stderr): string {
    return styleText(style, text, { stream });
}

/** Largura útil do terminal: sem terminal (teste, `--format table` em pipe), 100 colunas. */
export function terminalWidth(stream: NodeJS.WriteStream = process.stdout): number {
    return Math.max(60, Math.min(stream.columns || 100, 160));
}

const length = (text: string) => [...text].length;

function truncate(text: string, width: number): string {
    return length(text) <= width ? text : `${[...text].slice(0, Math.max(1, width - 1)).join('')}…`;
}

/** Quebra por palavras; palavra maior que a coluna é cortada. */
function wrap(text: string, width: number): string[] {
    const lines: string[] = [];
    let current = '';
    for (const word of text.split(/\s+/).filter(Boolean)) {
        if (current && length(current) + 1 + length(word) > width) {
            lines.push(current);
            current = '';
        }
        current = current ? `${current} ${word}` : truncate(word, width);
    }
    return [...lines, current];
}

export interface TableOptions {
    /** Largura total disponível. */
    width?: number;
    /** Recuo de cada linha. */
    indent?: number;
    /** Largura máxima de cada coluna, menos a última (que quebra em várias linhas). */
    max?: readonly (number | undefined)[];
    stream?: NodeJS.WriteStream;
}

/**
 * Tabela com cabeçalho. As colunas cortam com `…` no máximo pedido; a última ocupa o resto da linha
 * e quebra por palavras, para a explicação nunca sumir.
 */
export function table(headers: readonly string[], rows: readonly (readonly string[])[], options: TableOptions = {}): string[] {
    const { width = terminalWidth(options.stream), indent = 2, max = [], stream = process.stdout } = options;
    const gap = 3;
    const last = headers.length - 1;
    const widths = headers.map((header, column) => {
        const natural = Math.max(length(header), ...rows.map((row) => length(row[column] ?? '')));
        return column === last ? natural : Math.min(natural, max[column] ?? natural);
    });
    const fixed = widths.slice(0, last).reduce((sum, w) => sum + w + gap, indent);
    widths[last] = Math.max(16, Math.min(widths[last]!, width - fixed));
    const pad = ' '.repeat(indent);
    const line = (cells: readonly string[][]) => {
        const height = Math.max(...cells.map((c) => c.length));
        return Array.from({ length: height }, (_, i) => pad + cells.map((c, column) => {
            const text = c[i] ?? '';
            return column === last ? text : text + ' '.repeat(widths[column]! - length(text));
        }).join(' '.repeat(gap)).trimEnd());
    };
    const cellsOf = (row: readonly string[]) => row.map((cell, column) => (column === last ? wrap(cell, widths[last]!) : [truncate(cell, widths[column]!)]));
    const [head] = line(headers.map((h) => [h]));
    return [paint('bold', head!, stream), ...rows.flatMap((row) => line(cellsOf(row)))];
}

/** `1 value`, `3 values`. */
export function count(n: number, singular: string, plural = `${singular}s`): string {
    return `${n} ${n === 1 ? singular : plural}`;
}

/** Nome do tipo para pessoas: `font-size` → `font size`. */
export function typeLabel(type: string | undefined): string {
    return type ? type.replaceAll('-', ' ') : 'value';
}

/** Por que um arquivo foi pulado, em palavras. */
export function skipReasonText(reason: string): string {
    switch (reason) {
        case 'minified': return 'minified file';
        case 'generated': return 'generated by another tool';
        case 'too-large': return 'file too large';
        case 'binary': return 'not a text file';
        case 'symlink': return 'symbolic link';
        case 'unreadable': return 'could not be read';
        case 'unsupported': return 'file type not supported';
        default: return reason.replaceAll('-', ' ');
    }
}

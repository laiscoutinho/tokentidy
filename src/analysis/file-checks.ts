/**
 * O que o conteúdo diz sobre um arquivo antes de analisá-lo: minificado ou gerado por outra ferramenta.
 * As duas checagens leem o texto que já está em memória.
 */

/** Linha média acima disto: arquivo minificado (regra `minified_files?` do GitHub Linguist). */
const MINIFIED_AVERAGE_LINE = 110;

export function isMinified(source: string): boolean {
    const lines = source.split('\n');
    return source.length > 0 && source.length / lines.length > MINIFIED_AVERAGE_LINE;
}

/** Só o começo do arquivo: o aviso de arquivo gerado fica no cabeçalho. */
const HEADER_LENGTH = 600;

/** Avisos que geradores escrevem no topo (`@generated`, Style Dictionary, protoc, GraphQL Codegen, IcoMoon). */
const GENERATED_HEADER = /@generated\b|\bauto-?generated\b|\bgenerated by\b|\bdo not edit\b/i;

/** O cabeçalho do próprio TokenTidy: o `tokens.css` dele é arquivo de tokens e continua sendo lido. */
const TOKENTIDY_HEADER = /generated by tokentidy/i;

/**
 * Arquivo gerado por outra ferramenta: quem edita é o gerador, então um valor ali não é decisão de quem lê o relatório.
 * O arquivo ainda é lido para saber os tokens que define.
 */
export function isGeneratedFile(source: string): boolean {
    const header = source.slice(0, HEADER_LENGTH);
    return GENERATED_HEADER.test(header) && !TOKENTIDY_HEADER.test(header);
}

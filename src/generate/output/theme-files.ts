/**
 * Arquivos de modo do DTCG: um por tema, ligados por um Resolver (2025.10).
 * O token semântico também fica no `tokens.tokens.json`, com o valor claro: quem não usa o resolver continua com um valor.
 */

import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

import type { SemanticAlias } from '../semantic.ts';
import { DTCG_FILE, EXTENSION, OutputError, aliasTree } from './dtcg-tree.ts';
import type { DtcgTree } from './dtcg-tree.ts';

export const LIGHT_FILE = 'tokens.light.tokens.json';
export const DARK_FILE = 'tokens.dark.tokens.json';
export const RESOLVER_FILE = 'tokens.resolver.json';
/** Como o TokenTidy reconhece os próprios JSON antes de substituir. */
export const JSON_MARKER = 'Generated by TokenTidy';

export interface ThemeOutput {
    light: DtcgTree;
    dark: DtcgTree;
    selectors: string[];
    media: boolean;
}

async function readTree(file: string): Promise<DtcgTree | undefined> {
    if (!existsSync(file)) {
        return undefined;
    }
    try {
        return JSON.parse(await readFile(file, 'utf8')) as DtcgTree;
    } catch (error) {
        throw new OutputError(`Invalid JSON in ${file}: ${(error as Error).message}. Fix it or use --out to write elsewhere.`);
    }
}

interface ThemeMeta {
    selectors?: string[];
    media?: boolean;
}

const metaOf = (tree: DtcgTree | undefined): ThemeMeta => ((tree?.['$extensions'] as Record<string, unknown> | undefined)?.[EXTENSION] ?? {}) as ThemeMeta;

function sorted(selectors: Iterable<string>): string[] {
    return [...new Set(selectors)].sort();
}

/** No modo extend parte do que já existe: depois do `fix` não sobra valor solto para descobrir o tema de novo. */
export async function buildThemeOutput(
    outDir: string,
    tokens: { light: readonly SemanticAlias[]; dark: readonly SemanticAlias[]; selectors: readonly string[]; media: boolean },
    extend: boolean,
): Promise<ThemeOutput | undefined> {
    const [lightBefore, darkBefore] = extend ? await Promise.all([readTree(path.join(outDir, LIGHT_FILE)), readTree(path.join(outDir, DARK_FILE))]) : [undefined, undefined];
    if (tokens.dark.length === 0 && !darkBefore) {
        return undefined;
    }
    const meta = metaOf(darkBefore);
    const selectors = sorted([...(meta.selectors ?? []), ...tokens.selectors]);
    const media = meta.media === true || tokens.media;
    const stamp = (tree: DtcgTree, extension?: ThemeMeta): DtcgTree => ({
        $description: `${JSON_MARKER}. Edit tokens.tokens.json or the code and run \`tokentidy generate\` again.`,
        ...tree,
        ...(extension ? { $extensions: { [EXTENSION]: extension } } : {}),
    });
    return {
        light: stamp(aliasTree(tokens.light, lightBefore)),
        dark: stamp(aliasTree(tokens.dark, darkBefore), { selectors, media }),
        selectors,
        media,
    };
}

export function resolverContent(): string {
    return `${JSON.stringify({
        version: '2025.10',
        description: `${JSON_MARKER}: the base tokens plus one file per theme.`,
        sets: { foundation: { sources: [{ $ref: DTCG_FILE }] } },
        modifiers: { theme: { default: 'light', contexts: { light: [{ $ref: LIGHT_FILE }], dark: [{ $ref: DARK_FILE }] } } },
        resolutionOrder: [{ $ref: '#/sets/foundation' }, { $ref: '#/modifiers/theme' }],
    }, null, 2)}\n`;
}

/** O bloco do tema escuro no `tokens.css`, nas formas que o próprio projeto usa para ativá-lo. */
export function darkBlock(declarations: readonly string[], theme: Pick<ThemeOutput, 'selectors' | 'media'>): string {
    if (declarations.length === 0) {
        return '';
    }
    const body = declarations.join('\n');
    const blocks = theme.selectors.length > 0 ? [`${theme.selectors.join(',\n')} {\n${body}\n}\n`] : [];
    if (theme.media) {
        blocks.push(`@media (prefers-color-scheme: dark) {\n  :root {\n${declarations.map((line) => `  ${line}`).join('\n')}\n  }\n}\n`);
    }
    return `\n${blocks.join('\n')}`;
}

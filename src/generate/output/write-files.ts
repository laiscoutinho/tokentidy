/**
 * Escrita da pasta de tokens, cada arquivo de forma atômica. O TokenTidy só substitui ou apaga
 * arquivos que ele mesmo gerou.
 */

import { readdir, readFile, rm, rmdir } from 'node:fs/promises';
import path from 'node:path';

import { writeFileAtomic } from '../../safe-write.ts';
import { DTCG_FILE, OutputError, handWritten, readDtcgTree } from './dtcg-tree.ts';
import { SPLIT_DIR, isGenerated } from './render-files.ts';
import { DARK_FILE, LIGHT_FILE, RESOLVER_FILE } from './theme-files.ts';
import type { OutputFile, OutputFormats, WriteOptions } from './render-files.ts';
import type { ModuleLanguage } from './token-module.ts';

/** Arquivos que o TokenTidy gera: só eles são apagados no modo "começar do zero". */
const GENERATED_FILES = [DTCG_FILE, 'tokens.css', '_tokens.scss', '_tokens.less', 'tokens.ts', 'tokens.js', LIGHT_FILE, DARK_FILE, RESOLVER_FILE, 'README.md'];

async function readIfExists(file: string): Promise<string | undefined> {
    return readFile(file, 'utf8').catch((error: NodeJS.ErrnoException) => {
        if (error.code === 'ENOENT') {
            return undefined;
        }
        throw error;
    });
}

/** Formatos pedidos na linha de comando (`--dtcg`, `--scss`, `--less`, `--ts`, `--js`). */
export interface FormatRequest {
    dtcg?: boolean;
    scss?: boolean;
    less?: boolean;
    ts?: boolean;
    js?: boolean;
}

/**
 * Formatos a gerar além do CSS: os pedidos e os que já estão na pasta. Um formato gerado antes continua
 * sendo atualizado (o código pode importar o `_tokens.scss` ou o `tokens.ts`); para parar, basta apagar o arquivo.
 */
export async function chosenFormats(outDir: string, request: FormatRequest): Promise<{ formats: OutputFormats; modules: ModuleLanguage[] }> {
    const generated = async (name: string) => {
        const current = await readIfExists(path.join(outDir, name));
        return current !== undefined && isGenerated(current);
    };
    const exists = (name: string) => readIfExists(path.join(outDir, name)).then((content) => content !== undefined);
    const formats: OutputFormats = {
        dtcg: request.dtcg === true || await exists(DTCG_FILE) || await exists(LIGHT_FILE),
        scss: request.scss === true || await generated('_tokens.scss'),
        less: request.less === true || await generated('_tokens.less'),
    };
    const modules: ModuleLanguage[] = [];
    for (const language of ['js', 'ts'] as const) {
        if (request[language] === true || await generated(`tokens.${language}`)) {
            modules.push(language);
        }
    }
    return { formats, modules };
}

/**
 * Escreve os arquivos, cada um de forma atômica. Nunca substitui nem apaga arquivo de outra pessoa:
 * - um `tokens.css`/`_tokens.scss`/`README.md` sem o cabeçalho do TokenTidy interrompe tudo antes de escrever;
 * - no modo "começar do zero", um `tokens.tokens.json` com tokens escritos à mão também;
 * - sobras de uma geração anterior (`css/color.css` que não existe mais) são apagadas só se forem do TokenTidy.
 */
export async function writeOutput(files: readonly OutputFile[], options: WriteOptions): Promise<void> {
    for (const { file } of files) {
        const current = await readIfExists(file);
        if (current === undefined) {
            continue;
        }
        if (path.basename(file) === DTCG_FILE) {
            const tree = options.mode === 'new' ? await readDtcgTree(path.dirname(file)) : undefined;
            const manual = tree ? handWritten(tree) : [];
            if (manual.length > 0) {
                throw new OutputError(`${file} has tokens not generated by TokenTidy (${manual.slice(0, 3).join(', ')}${manual.length > 3 ? ', ...' : ''}); --new would delete them. Use --extend or --out.`);
            }
        } else if (!isGenerated(current)) {
            throw new OutputError(`${file} was not generated by TokenTidy; not overwriting it. Use --out to write elsewhere.`);
        }
    }

    // Sobras da geração anterior (o CSS deixou de ser dividido, o projeto parou de usar Less)
    const keep = new Set(files.map((f) => f.file));
    const splitDir = path.join(options.outDir, SPLIT_DIR);
    const split = (await readdir(splitDir).catch(() => [] as string[])).filter((name) => name.endsWith('.css')).map((name) => path.join(SPLIT_DIR, name));
    for (const name of [...GENERATED_FILES.filter((n) => n !== DTCG_FILE), ...split]) {
        const file = path.join(options.outDir, name);
        const current = keep.has(file) ? undefined : await readIfExists(file);
        if (current !== undefined && isGenerated(current)) {
            await rm(file, { force: true });
        }
    }
    // Só se ficou vazia: a pasta pode ter arquivos da pessoa
    await rmdir(splitDir).catch(() => undefined);
    for (const { file, content } of files) {
        await writeFileAtomic(file, content);
    }
}

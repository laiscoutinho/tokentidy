// Valor lido pelo JavaScript: `var()` não funciona ali, então entra o caminho no módulo gerado. E o resultado compila.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { CLI_ENTRY, tempDir } from '../helpers.ts';

const TSC = path.resolve(import.meta.dirname, '../../node_modules/.bin/tsc');

async function withProject<T>(files: Record<string, string>, run: (dir: string) => Promise<T>): Promise<T> {
    const dir = await tempDir();
    try {
        for (const [name, content] of Object.entries({ 'package.json': '{}\n', ...files })) {
            await mkdir(path.dirname(path.join(dir, name)), { recursive: true });
            await writeFile(path.join(dir, name), content);
        }
        return await run(dir);
    } finally {
        await rm(dir, { recursive: true, force: true });
    }
}

const cli = (dir: string, ...args: string[]) => spawnSync(process.execPath, [CLI_ENTRY, ...args], { encoding: 'utf8', cwd: dir, input: '' });

const CANVAS = "const ctx = document.querySelector('canvas')!.getContext('2d')!;\nctx.fillStyle = '#4f46e5';\nctx.strokeStyle = '#4f46e5';\n";

function typeCheck(dir: string, ...files: string[]) {
    return spawnSync(TSC, ['--ignoreConfig', '--noEmit', '--strict', '--target', 'esnext', '--module', 'esnext', '--moduleResolution', 'bundler', '--lib', 'dom,esnext', '--types', '', ...files], { encoding: 'utf8', cwd: dir });
}

test('canvas: the token module is generated, imported, and type-checks', () => withProject({ 'src/draw.ts': CANVAS }, async (dir) => {
    assert.equal(cli(dir, 'generate', '.').status, 0);
    const module = await readFile(path.join(dir, 'design-tokens/tokens.ts'), 'utf8');
    assert.match(module, /^\/\/ Generated by TokenTidy/);
    assert.match(module, /export const color = \{/);
    assert.match(module, /'#4f46e5'/);
    assert.match(module, /\} as const;/);

    const fix = cli(dir, 'fix', '.');
    assert.equal(fix.status, 0, fix.stderr);
    const fixed = await readFile(path.join(dir, 'src/draw.ts'), 'utf8');
    assert.match(fixed, /^import \{ color \} from '\.\.\/design-tokens\/tokens';\n/);
    assert.match(fixed, /ctx\.fillStyle = color\.[\w.[\]]+;/);
    assert.doesNotMatch(fixed, /#4f46e5/);

    const check = typeCheck(dir, 'src/draw.ts');
    assert.equal(check.status, 0, check.stdout + check.stderr);
}));

test('the module survives once no loose value is left', () => withProject({ 'src/draw.ts': CANVAS }, async (dir) => {
    cli(dir, 'generate', '.');
    cli(dir, 'fix', '.');
    assert.equal(cli(dir, 'generate', '.', '--extend').status, 0);
    assert.ok(existsSync(path.join(dir, 'design-tokens/tokens.ts')));
    assert.equal(cli(dir, 'check', '.').status, 0);
}));

test('a project without values read by JavaScript gets no module', () => withProject({ 'a.css': '.a { color: #4f46e5; }\n.b { color: #4f46e5; }\n' }, async (dir) => {
    assert.equal(cli(dir, 'generate', '.').status, 0);
    assert.equal(existsSync(path.join(dir, 'design-tokens/tokens.ts')), false);
}));

test('a local named like the export gets the import under another name', () => withProject({
    'src/draw.ts': "const color = document.querySelector('canvas')!.getContext('2d')!;\ncolor.fillStyle = '#4f46e5';\ncolor.strokeStyle = '#4f46e5';\n",
}, async (dir) => {
    cli(dir, 'generate', '.');
    cli(dir, 'fix', '.');
    const fixed = await readFile(path.join(dir, 'src/draw.ts'), 'utf8');
    assert.match(fixed, /import \{ color as tokenColor \}/);
    assert.match(fixed, /color\.fillStyle = tokenColor\./);
    const check = typeCheck(dir, 'src/draw.ts');
    assert.equal(check.status, 0, check.stdout + check.stderr);
}));

test('the import goes after directives and existing imports', () => withProject({
    'src/a.tsx': "'use client';\nimport { x } from './x';\nexport const draw = (c: CanvasRenderingContext2D) => { c.fillStyle = '#4f46e5'; c.strokeStyle = '#4f46e5'; return x; };\n",
    'src/x.ts': 'export const x = 1;\n',
}, async (dir) => {
    cli(dir, 'generate', '.');
    cli(dir, 'fix', '.');
    const fixed = await readFile(path.join(dir, 'src/a.tsx'), 'utf8');
    assert.match(fixed, /^'use client';\nimport \{ x \} from '\.\/x';\nimport \{ color \} from '\.\.\/design-tokens\/tokens';\n/);
}));

test('an existing import of the module is extended, not repeated', () => withProject({ 'src/draw.ts': CANVAS }, async (dir) => {
    cli(dir, 'generate', '.');
    await writeFile(path.join(dir, 'src/more.ts'), "import { color } from '../design-tokens/tokens';\nexport const a = color;\nexport const paint = (c: CanvasRenderingContext2D) => { c.fillStyle = '#4f46e5'; };\n");
    cli(dir, 'fix', '.');
    const fixed = await readFile(path.join(dir, 'src/more.ts'), 'utf8');
    assert.equal(fixed.match(/from '\.\.\/design-tokens\/tokens'/g)?.length, 1);
    assert.match(fixed, /c\.fillStyle = color\./);
}));

test('a JavaScript module imports tokens.js with its extension', () => withProject({ 'src/draw.js': "export const paint = (c) => { c.fillStyle = '#4f46e5'; c.strokeStyle = '#4f46e5'; };\n" }, async (dir) => {
    cli(dir, 'generate', '.');
    assert.doesNotMatch(await readFile(path.join(dir, 'design-tokens/tokens.js'), 'utf8'), /as const/);
    cli(dir, 'fix', '.');
    assert.match(await readFile(path.join(dir, 'src/draw.js'), 'utf8'), /from '\.\.\/design-tokens\/tokens\.js';/);
}));

test('a script without import or export is left alone, with the reason', () => withProject({ 'src/draw.js': "var c = document.querySelector('canvas').getContext('2d');\nc.fillStyle = '#4f46e5';\nc.strokeStyle = '#4f46e5';\n" }, async (dir) => {
    cli(dir, 'generate', '.');
    const fix = cli(dir, 'fix', '.');
    assert.match(fix.stderr, /needs-token-module/);
    assert.match(await readFile(path.join(dir, 'src/draw.js'), 'utf8'), /#4f46e5/);
}));

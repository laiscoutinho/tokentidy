test('two findings on the same text: the second one is skipped as overlap', () => {
    const finding: Finding = {
        file: 'a.css', line: 1, column: 15, offset: 14, endOffset: 18, type: 'spacing', rule: 'spacing/hardcoded',
        property: 'padding', value: '16px', host: 'css',
    };
    const index = buildTokenIndex({
        definitions: [], references: [],
        generated: [{ path: ['spacing', '4'], type: 'spacing', key: '16px', occurrences: [] }],
        outputs: { css: true, scss: false, less: false },
    });
    const plan = planFixes([finding, { ...finding }], {
        index, sources: new Map([['a.css', '.a { padding: 16px; }']]), generatedFiles: { scss: 't/_tokens.scss', less: 't/_tokens.less' },
    });

    assert.equal(plan.files[0]!.replacements.length, 1);
    assert.deepEqual(plan.skipped.map((s) => s.reason), ['overlap']);
});

test('operators: * / + % always, - only with a space after it', () => {
    const at = (text: string) => {
        const start = text.indexOf('16px');
        return nextToOperator(text, start, start + 4);
    };
    assert.equal(at('a: 16px * 2'), true);
    assert.equal(at('a: 2*16px'), true);
    assert.equal(at('a: $x + 16px'), true);
    assert.equal(at('a: $x - 16px'), true);
    assert.equal(at('a: 16px -$x'), false);
    assert.equal(at('a: 16px 8px'), false);
});

test('unified diff: separate hunks, missing newline at the end, CRLF and an empty file', () => {
    const source = Array.from({ length: 12 }, (_, i) => `line ${i + 1}`).join('\n');
    const at = (n: number) => source.indexOf(`line ${n}`);
    const diff = unifiedDiff('f.txt', source, [
        { offset: at(1), endOffset: at(1) + 6, text: 'LINE 1' },
        { offset: at(12), endOffset: source.length, text: 'LINE 12' },
    ]);
    assert.equal(diff, [
        '--- a/f.txt', '+++ b/f.txt',
        '@@ -1,4 +1,4 @@', '-line 1', '+LINE 1', ' line 2', ' line 3', ' line 4',
        '@@ -9,4 +9,4 @@', ' line 9', ' line 10', ' line 11', '-line 12', '\\ No newline at end of file', '+LINE 12', '\\ No newline at end of file', '',
    ].join('\n'));

    assert.equal(unifiedDiff('w.css', 'a\r\nb\r\n', [{ offset: 0, endOffset: 1, text: 'x' }]), '--- a/w.css\n+++ b/w.css\n@@ -1,2 +1,2 @@\n-a\r\n+x\r\n b\r\n');
    assert.equal(unifiedDiff('e.scss', '', [{ offset: 0, endOffset: 0, text: '@use "t" as *;\n' }]), '--- a/e.scss\n+++ b/e.scss\n@@ -0,0 +1 @@\n+@use "t" as *;\n');
    assert.equal(unifiedDiff('same.css', 'a', [{ offset: 0, endOffset: 1, text: 'a' }]), '');
    assert.equal(applyEdits('abcdef', [{ offset: 0, endOffset: 1, text: 'X' }, { offset: 4, endOffset: 4, text: '-' }]), 'Xbcd-ef');
});

test('imports: what a stylesheet loads, and where the tokens import goes', () => {
    assert.deepEqual(loadedFiles("@use 'sass:math';\n@use '../t/tokens' as *;\n@use 'vars' as v;\n@import 'mixins', 'x';\n@import (reference) '~lib/a';\n", 'src/a.scss'), [
        { id: 't/tokens', global: true },
        { id: 'src/vars', global: false },
        { id: 'src/mixins', global: true },
    ]);

    const scss = importInsertion("@charset 'utf-8';\n// note\n@use 'sass:math';\n.a {}\n", 'scss', 'design-tokens/_tokens.scss', 'src/a.scss');
    assert.deepEqual(scss, { offset: 44, text: "@use '../design-tokens/tokens' as *;\n" });
    assert.deepEqual(importInsertion('﻿.a {}\r\n', 'scss', '_tokens.scss', 'a.scss'), { offset: 1, text: "@use './tokens' as *;\r\n" });
    assert.deepEqual(importInsertion('@import "x";', 'less', 't/_tokens.less', 'a.less'), { offset: 12, text: "\n@import (reference) './t/_tokens.less';\n" });
    assert.deepEqual(importInsertion('@use "x"\n.a\n  b: c\n', 'sass', '_tokens.scss', 'a.sass'), { offset: 9, text: "@use './tokens' as *\n" });
});

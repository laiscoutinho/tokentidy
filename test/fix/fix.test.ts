test('SCSS: a hand-written $variable is used where it is visible, and the generated one is not imported twice', async () => {
    const dir = await project({
        'src/_vars.scss': '$gap: 16px;\n',
        'src/a.scss': "@import 'vars';\n.a { padding: 16px * 2; }\n.u { gap: $gap; }\n",
        'src/b.scss': "@use '../design-tokens/tokens' as *;\n.b { padding: 16px * 2; }\n",
        'src/c.scss': "@use '../design-tokens/tokens' as t;\n.c { padding: 16px * 2; }\n",
    }, { scss: true });
    try {
        const result = await fix(dir);

        assert.equal(await read(dir, 'src/a.scss'), "@import 'vars';\n.a { padding: $gap * 2; }\n.u { gap: $gap; }\n");
        assert.equal(await read(dir, 'src/b.scss'), "@use '../design-tokens/tokens' as *;\n.b { padding: $spacing-4 * 2; }\n");
        assert.deepEqual(result.skipped.map((s) => `${s.finding.file}:${s.reason}`), ['src/c.scss:variable-not-loaded']);
    } finally {
        await rm(dir, { recursive: true });
    }
});

test('Sass (indented) gets @use without a semicolon; Less gets @import (reference) and its own variables', async () => {
    const dir = await project({
        'src/a.sass': '.a\n  padding: 16px * 2\n',
        'src/b.less': '@gap: 16px;\n.u { gap: @gap; }\n.b { margin: 16px; }\n.c { padding: (16px * 2); }\n',
        'src/c.less': '.d { padding: (16px * 2); }\n',
    }, { scss: true, less: true });
    try {
        await fix(dir);

        assert.equal(await read(dir, 'src/a.sass'), "@use '../design-tokens/tokens' as *\n.a\n  padding: $spacing-4 * 2\n");
        assert.equal(await read(dir, 'src/b.less'), '@gap: 16px;\n.u { gap: @gap; }\n.b { margin: @gap; }\n.c { padding: (@gap * 2); }\n');
        assert.equal(await read(dir, 'src/c.less'), "@import (reference) '../design-tokens/_tokens.less';\n.d { padding: (@spacing-4 * 2); }\n");
    } finally {
        await rm(dir, { recursive: true });
    }
});


/** Tokens gerados como o `generate` escreve: `spacing.4` = 16px, `radius.md` = 6px, `breakpoint.md` = 768px, `color.indigo.600`. */
const GENERATED = {
    spacing: { 4: token('dimension', { value: 16, unit: 'px' }, 'spacing', '16px') },
    radius: { md: token('dimension', { value: 6, unit: 'px' }, 'radius', '6px') },
    breakpoint: { md: token('dimension', { value: 768, unit: 'px' }, 'breakpoint', '768px') },
    color: {
        indigo: { 600: token('color', { colorSpace: 'srgb', components: [0.31, 0.275, 0.898], hex: '#4f46e5' }, 'color', '#4f46e5') },
        text: {
            danger: {
                $type: 'color',
                $value: '{color.indigo.600}',
                $extensions: { 'dev.tokentidy': { occurrences: [{ file: 'src/alert.css', property: 'color', selector: '.alert' }] } },
            },
        },
    },
};

function token($type: string, $value: unknown, type: string, key: string) {
    return { $type, $value, $extensions: { 'dev.tokentidy': { type, key } } };
}

async function project(files: Record<string, string>, generated: { scss?: boolean; less?: boolean } = {}): Promise<string> {
    const dir = await tempDir();
    await writeFile(path.join(dir, 'package.json'), '{"name":"app"}');
    for (const [file, content] of Object.entries(files)) {
        await mkdir(path.dirname(path.join(dir, file)), { recursive: true });
        await writeFile(path.join(dir, file), content);
    }
    const tokens = path.join(dir, 'design-tokens');
    await mkdir(tokens, { recursive: true });
    await writeFile(path.join(tokens, 'tokens.tokens.json'), JSON.stringify(GENERATED));
    await writeFile(path.join(tokens, 'tokens.css'), '/* Generated by TokenTidy */\n:root { --spacing-4: 16px; }\n');
    if (generated.scss) {
        await writeFile(path.join(tokens, '_tokens.scss'), '$spacing-4: 16px;\n');
    }
    if (generated.less) {
        await writeFile(path.join(tokens, '_tokens.less'), '@spacing-4: 16px;\n');
    }
    return dir;
}

async function fix(dir: string, options: { dryRun?: boolean; sources?: Map<string, string>; paths?: string[] } = {}): Promise<FixResult> {
    const { paths = [dir], ...rest } = options;
    return fixScope(await collectFiles(paths, dir), { tokensDir: path.join(dir, 'design-tokens'), ...rest });
}

const read = (dir: string, file: string) => readFile(path.join(dir, file), 'utf8');

test('CSS: project tokens first, then generated ones, then the semantic alias for its own occurrence', async () => {
    const dir = await project({
        'src/theme.css': ':root { --brand: #4f46e5; }\n.x { color: var(--brand); }\n',
        'src/a.css': '.a { color: #4F46E5; padding: 16px; margin: 8px 16px; border-radius: 6px; }\n',
        'src/alert.css': '.alert { color: #4f46e5; }\n',
    });
    try {
        const result = await fix(dir);

        assert.equal(await read(dir, 'src/a.css'), '.a { color: var(--brand); padding: var(--spacing-4); margin: 8px var(--spacing-4); border-radius: var(--radius-md); }\n');
        assert.equal(await read(dir, 'src/alert.css'), '.alert { color: var(--color-text-danger); }\n');
        const sources = result.files.flatMap((f) => f.replacements.map((r) => `${r.token}:${r.source}`));
        assert.deepEqual(sources.sort(), ['--brand:project', '--color-text-danger:alias', '--radius-md:generated', '--spacing-4:generated', '--spacing-4:generated']);
        assert.deepEqual(result.after.findings.map((f) => f.value), ['8px']);
        assert.equal(result.withoutToken.length, 1);
    } finally {
        await rm(dir, { recursive: true });
    }
});


test('symbolic links and files that differ from what was analyzed are not written', async () => {
    const dir = await project({ 'real/a.css': '.a { padding: 16px; }\n', 'src/b.css': '.b { padding: 16px; }\n' });
    try {
        await symlink(path.join(dir, 'real', 'a.css'), path.join(dir, 'src', 'link.css'));
        // O conteúdo analisado (em memória) não é o do disco: as posições não valem mais
        const sources = new Map([['src/b.css', '.b {   padding: 16px; }\n']]);
        // A pasta não segue links; o link só entra quando é passado pelo nome
        const result = await fix(dir, { sources, paths: [path.join(dir, 'src', 'b.css'), path.join(dir, 'src', 'link.css')] });

        assert.deepEqual(result.skipped.map((s) => `${s.finding.file}:${s.reason}`), ['src/b.css:changed-on-disk', 'src/link.css:symlink']);
        assert.equal(await read(dir, 'src/b.css'), '.b { padding: 16px; }\n');
        assert.equal(await read(dir, 'real/a.css'), '.a { padding: 16px; }\n');
    } finally {
        await rm(dir, { recursive: true });
    }
});

test('--dry-run writes nothing and a second fix finds nothing to replace', async () => {
    const dir = await project({ 'src/a.css': '.a {\n  padding: 16px;\n  border-radius: 6px;\n}\n' });
    try {
        const preview = await fix(dir, { dryRun: true });
        assert.equal(await read(dir, 'src/a.css'), '.a {\n  padding: 16px;\n  border-radius: 6px;\n}\n');
        assert.equal(preview.files[0]!.diff, [
            '--- a/src/a.css', '+++ b/src/a.css', '@@ -1,4 +1,4 @@', ' .a {',
            '-  padding: 16px;', '-  border-radius: 6px;', '+  padding: var(--spacing-4);', '+  border-radius: var(--radius-md);', ' }', '',
        ].join('\n'));

        await fix(dir);
        const again = await fix(dir, { dryRun: true });
        assert.equal(again.files.length, 0);
        assert.equal(again.after.findings.length, 0);
    } finally {
        await rm(dir, { recursive: true });
    }
});

test('the CLI exits with 1 while violations remain, 0 when clean, and --json is valid', async () => {
    const dir = await project({ 'src/a.css': '.a { padding: 16px; }\n', 'src/b.css': '.b { margin: 8px; }\n' });
    const run = (...args: string[]) => spawnSync(process.execPath, [CLI_ENTRY, 'fix', ...args], { encoding: 'utf8', cwd: dir });
    try {
        const dry = run('--dry-run');
        assert.equal(dry.status, 1);
        assert.match(dry.stdout, /^--- a\/src\/a\.css\n\+\+\+ b\/src\/a\.css\n@@ -1 \+1 @@\n-\.a \{ padding: 16px; \}\n\+\.a \{ padding: var\(--spacing-4\); \}\n$/);
        assert.match(dry.stderr, /1 value would be replaced in 1 file; 0 skipped; 1 without a token; 1 violation remains/);

        const json = run('src/a.css', '--json');
        assert.equal(json.status, 0);
        const data = JSON.parse(json.stdout);
        assert.equal(data.files[0].replacements[0].token, '--spacing-4');
        assert.deepEqual(data.remaining, []);

        const clean = run('src/a.css');
        assert.equal(clean.status, 0);
        assert.equal(clean.stdout, '');
    } finally {
        await rm(dir, { recursive: true });
    }
});


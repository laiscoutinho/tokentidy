// O `tokens.css` gerado é a fonte: o que a pessoa muda nele vale no próximo `generate` e no `fix`.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { readTokenState } from '../../src/generate/output/css-state.ts';
import { chosenFormats } from '../../src/generate/output/write-files.ts';
import { CLI_ENTRY, tempDir } from '../helpers.ts';

const HEADER = '/* Generated by TokenTidy. You can edit names and values here: `tokentidy generate` keeps your changes. */\n';

async function withDir<T>(files: Record<string, string>, run: (dir: string) => Promise<T>): Promise<T> {
    const dir = await tempDir();
    try {
        for (const [name, content] of Object.entries(files)) {
            await mkdir(path.dirname(path.join(dir, name)), { recursive: true });
            await writeFile(path.join(dir, name), content);
        }
        return await run(dir);
    } finally {
        await rm(dir, { recursive: true, force: true });
    }
}

const cli = (dir: string, ...args: string[]) => spawnSync(process.execPath, [CLI_ENTRY, ...args], { encoding: 'utf8', cwd: dir, input: '' });

test('names, values and categories come from tokens.css, nested as generate nests them', () => withDir({
    'tokens.css': `${HEADER}:root {\n  /* color */\n  --color-indigo-600: #4f46e5;\n  --color-brand: var(--color-indigo-600);\n\n  /* spacing */\n  --spacing-4: 16px;\n}\n`,
}, async (dir) => {
    const state = await readTokenState(dir);
    const tree = state!.tree as Record<string, Record<string, Record<string, { $value: unknown; $type: string }>>>;
    assert.equal(tree.color!.indigo!['600']!.$type, 'color');
    assert.equal(tree.color!.brand!.$value, '{color.indigo.600}');
    assert.deepEqual(tree.spacing!['4']!.$value, { value: 16, unit: 'px' });
    assert.equal(state!.dark, undefined);
}));

test('a token inside another keeps its full name instead of breaking the tree', () => withDir({
    'tokens.css': `${HEADER}:root {\n  /* color */\n  --color-gray: #888888;\n  --color-gray-900: #111111;\n}\n`,
}, async (dir) => {
    const tree = (await readTokenState(dir))!.tree as Record<string, Record<string, unknown>>;
    assert.deepEqual(Object.keys(tree.color!).sort(), ['gray', 'gray-900']);
}));

test('the JSON only gives back paths and occurrences of tokens whose name and value did not change in the CSS', () => withDir({
    'tokens.tokens.json': JSON.stringify({
        spacing: { 4: { $type: 'dimension', $value: { value: 16, unit: 'px' }, $extensions: { 'dev.tokentidy': { type: 'spacing', key: '16px', occurrences: [{ file: 'a.css' }] } } } },
        radius: { md: { $type: 'dimension', $value: { value: 6, unit: 'px' }, $extensions: { 'dev.tokentidy': { type: 'radius', key: '6px' } } } },
    }),
    'tokens.css': `${HEADER}:root {\n  /* spacing */\n  --spacing-4: 16px;\n  /* radius */\n  --radius-md: 8px;\n}\n`,
}, async (dir) => {
    const tree = (await readTokenState(dir))!.tree as Record<string, Record<string, { $value: { value: number }; $extensions: Record<string, { occurrences: unknown[] }> }>>;
    assert.equal(tree.spacing!['4']!.$extensions['dev.tokentidy']!.occurrences.length, 1);
    assert.equal(tree.radius!.md!.$value.value, 8);
    assert.equal(tree.radius!.md!.$extensions['dev.tokentidy']!.occurrences, undefined);
}));

test('the dark block is read from a selector and from prefers-color-scheme', () => withDir({
    'tokens.css': `${HEADER}:root {\n  /* color */\n  --color-white: #ffffff;\n  --color-gray-800: #1f2937;\n  --color-bg-card: var(--color-white);\n}\n\n.dark {\n  --color-bg-card: var(--color-gray-800);\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n    --color-bg-card: var(--color-gray-800);\n  }\n}\n`,
}, async (dir) => {
    const { dark } = (await readTokenState(dir))!;
    assert.deepEqual(dark!.selectors, ['.dark']);
    assert.equal(dark!.media, true);
    assert.equal((dark!.tree as Record<string, Record<string, Record<string, { $value: string }>>>).color!.bg!.card!.$value, '{color.gray.800}');
    assert.equal((dark!.light as Record<string, Record<string, Record<string, { $value: string }>>>).color!.bg!.card!.$value, '{color.white}');
}));

test('a tokens.css written by hand is not read as generated; broken CSS falls back to the JSON', async () => {
    await withDir({ 'tokens.css': ':root { --a: 1px; }\n' }, async (dir) => assert.equal(await readTokenState(dir), undefined));
    await withDir({
        'tokens.css': `${HEADER}:root { --a: 1px;\n`,
        'tokens.tokens.json': JSON.stringify({ a: { $type: 'dimension', $value: { value: 1, unit: 'px' } } }),
    }, async (dir) => assert.ok((await readTokenState(dir))!.tree.a));
});

test('split files imported by tokens.css are read too', () => withDir({
    'tokens.css': `${HEADER}@import "./css/color.css";\n`,
    'css/color.css': `${HEADER}:root {\n  /* color */\n  --color-white: #ffffff;\n}\n`,
}, async (dir) => {
    assert.ok(((await readTokenState(dir))!.tree as Record<string, Record<string, unknown>>).color!.white);
}));

test('formats: CSS always; the others when asked for, or when the folder already has them', () => withDir({
    '_tokens.scss': '// Generated by TokenTidy from tokens.css.\n$a: 1px;\n',
    'tokens.ts': '// Generated by TokenTidy from tokens.css.\nexport const a = 1;\n',
}, async (dir) => {
    assert.deepEqual(await chosenFormats(dir, {}), { formats: { dtcg: false, scss: true, less: false }, modules: ['ts'] });
    assert.deepEqual(await chosenFormats(dir, { dtcg: true, less: true, js: true }), { formats: { dtcg: true, scss: true, less: true }, modules: ['js', 'ts'] });
    assert.deepEqual(await chosenFormats(path.join(dir, 'missing'), {}), { formats: { dtcg: false, scss: false, less: false }, modules: [] });
}));

test('a name and a value changed in tokens.css, and a token added there, survive generate --extend and are used by fix', () => withDir({
    'package.json': '{}\n',
    'a.css': '.a { color: #4f46e5; }\n.b { color: #4f46e5; }\n.c { color: #4f46e5; }\n',
}, async (dir) => {
    assert.equal(cli(dir, 'generate', '.').status, 0);
    const file = path.join(dir, 'design-tokens/tokens.css');
    await writeFile(file, (await readFile(file, 'utf8')).replace('--color-indigo-600: #4f46e5;', '--color-brand: #4f46e5;\n  --color-extra: #000000;'));

    const again = cli(dir, 'generate', '.', '--extend');
    assert.equal(again.status, 0, again.stderr);
    assert.match(again.stderr, /✔ 2 tokens \(0 new\)/);
    const css = await readFile(file, 'utf8');
    assert.match(css, /--color-brand: #4f46e5;/);
    assert.match(css, /--color-extra: #000000;/);
    assert.doesNotMatch(css, /indigo/);
    assert.doesNotMatch(css, /edit .*json/i);

    assert.equal(cli(dir, 'fix', '.').status, 0);
    assert.equal(await readFile(path.join(dir, 'a.css'), 'utf8'), '.a { color: var(--color-brand); }\n.b { color: var(--color-brand); }\n.c { color: var(--color-brand); }\n');
}));

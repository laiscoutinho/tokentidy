// Temas: o mesmo papel com um valor por modo vira um token semântico, e o resultado passa no `validate`.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

import { CLI_ENTRY, tempDir } from '../helpers.ts';

async function withProject<T>(css: string, run: (dir: string) => Promise<T>): Promise<T> {
    const dir = await tempDir();
    try {
        await writeFile(path.join(dir, 'package.json'), '{}\n');
        await writeFile(path.join(dir, 'a.css'), css);
        return await run(dir);
    } finally {
        await rm(dir, { recursive: true, force: true });
    }
}

const cli = (dir: string, ...args: string[]) => spawnSync(process.execPath, [CLI_ENTRY, ...args], { encoding: 'utf8', cwd: dir, input: '' });
const output = (dir: string, name: string) => readFile(path.join(dir, 'design-tokens', name), 'utf8');
const themesOf = (dir: string) => JSON.parse(cli(dir, 'generate', '.', '--json', '--dry-run').stdout).themes as { path: string[] }[];

const DARK = '.card { background: #ffffff; color: #111111; }\n.dark .card { background: #1f2937; color: #e5e7eb; }\n';

test('a dark theme produces semantic tokens per mode', () => withProject(DARK, async (dir) => {
    assert.equal(cli(dir, 'generate', '.').status, 0);
    const css = await output(dir, 'tokens.css');
    assert.match(css, /:root \{[^}]*--color-bg-card: var\(--color-white\);/);
    assert.match(css, /\.dark \{\n {2}--color-bg-card: var\(--color-gray-\d+\);/);
    const dark = JSON.parse(await output(dir, 'tokens.dark.tokens.json'));
    const light = JSON.parse(await output(dir, 'tokens.light.tokens.json'));
    assert.match(dark.color.bg.card.$value, /^\{color\.gray/);
    assert.equal(light.color.bg.card.$value, '{color.white}');
    assert.equal(JSON.parse(await output(dir, 'tokens.resolver.json')).version, '2025.10');
    const validated = cli(dir, 'validate', '.');
    assert.equal(validated.status, 0, validated.stdout + validated.stderr);
}));

test('values used once still become tokens when they are a theme pair', () => withProject(DARK, async (dir) => {
    assert.equal(themesOf(dir).length, 2);
}));

test('fix uses the same semantic token in both modes, and generating again keeps the theme', () => withProject(DARK, async (dir) => {
    cli(dir, 'generate', '.');
    assert.equal(cli(dir, 'fix', '.').status, 0);
    assert.equal(await readFile(path.join(dir, 'a.css'), 'utf8'), '.card { background: var(--color-bg-card); color: var(--color-text-card); }\n.dark .card { background: var(--color-bg-card); color: var(--color-text-card); }\n');
    const before = await output(dir, 'tokens.css');
    assert.equal(cli(dir, 'generate', '.', '--extend').status, 0);
    assert.equal(await output(dir, 'tokens.css'), before);
    assert.equal(cli(dir, 'validate', '.').status, 0);
}));

test('each way of writing the dark theme is kept in the CSS', () => withProject(`.a { color: #111111; }
[data-theme="dark"] .a { color: #eeeeee; }
.b { color: #222222; }
@media (prefers-color-scheme: dark) { .b { color: #dddddd; } }
`, async (dir) => {
    cli(dir, 'generate', '.');
    const css = await output(dir, 'tokens.css');
    assert.match(css, /\[data-theme="dark"\] \{/);
    assert.match(css, /@media \(prefers-color-scheme: dark\) \{\n {2}:root \{/);
}));

test('the page itself is the default role', () => withProject('body { background: #ffffff; }\n.dark { background: #000000; }\n', async (dir) => {
    assert.deepEqual(themesOf(dir).map((t) => t.path.join('.')), ['color.bg.default']);
}));

test('two values in one role and mode generate nothing', () => withProject('.a { color: #111111; }\n.dark .a { color: #eeeeee; }\n.dark .x .a { color: #dddddd; }\n', async (dir) => {
    assert.deepEqual(themesOf(dir), []);
}));

test('a value only in one mode, a responsive rule or .darker are not themes', async () => {
    await withProject('.a { color: #111111; }\n', async (dir) => assert.deepEqual(themesOf(dir), []));
    await withProject('.dark .a { color: #111111; }\n', async (dir) => assert.deepEqual(themesOf(dir), []));
    await withProject('.a { color: #111111; }\n@media (min-width: 600px) { .a { color: #eeeeee; } }\n', async (dir) => assert.deepEqual(themesOf(dir), []));
    await withProject('.a { color: #111111; }\n.darker .a { color: #eeeeee; }\n', async (dir) => assert.deepEqual(themesOf(dir), []));
});

test('a theme file written by someone else is not overwritten', () => withProject(DARK, async (dir) => {
    cli(dir, 'generate', '.');
    await writeFile(path.join(dir, 'design-tokens/tokens.resolver.json'), '{"version":"2025.10","resolutionOrder":[]}\n');
    const result = cli(dir, 'generate', '.', '--extend');
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /not generated by TokenTidy/);
}));
